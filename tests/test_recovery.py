"""Tests for the planted ground-truth recovery benchmarks.

Three things are pinned, each corresponding to a way the first version of this
benchmark lied:

* It reported ``R^2 = 1.000000`` beside a 70% error on ``D`` and a 2400% error on
  clearance, because the planted pair was **not identifiable**. Identifiability is
  now a precondition, and a non-identifiable pair is refused rather than fitted.
* It regressed a forward-Euler difference against the analytic Laplacian, leaving
  the ``O(dt)`` term unmodeled. That produced coefficients an order of magnitude
  wrong at R^2 = 0.9997. The derivative is now a second-order central difference.
* The ground truth must come from an **independent** solver. If the field were
  generated by advancing the engine's own operator, inverting it would recover
  the planted constants to machine precision and prove nothing.
"""


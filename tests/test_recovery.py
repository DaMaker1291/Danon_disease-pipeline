class TestEstimatorSpecification:
    def test_forward_difference_would_bias_the_fit(self):
        """Pins why the derivative must be second-order.

        Regressing the forward difference against ``Lap(C^n)`` leaves the
        ``O(dt)*d2C/dt2`` term unmodeled; at a coarse step the fitted D is wrong
        by an order of magnitude even though the fit looks excellent. This test
        demonstrates the failure so the fix cannot be silently reverted.
        """
        D, lam, g = 0.35, 0.10, 32
        kw = dict(planted_d=D, planted_lambda=lam, grid_size=g, sigma_voxels=2.5)
        times = infer_times(D, lam, sigma_voxels=2.5, n_times=8)
        fields = analytic_point_source_field(times=times, **kw)

        # A deliberately coarse forward difference, as the first version did.
        dt_coarse = 0.25 * (times[1] - times[0])
        fwd = np.gradient(fields, dt_coarse, axis=0)
        from danon.recovery import _engine_laplacian

        lap = _engine_laplacian(fields[0])
        A = np.column_stack([lap.ravel(), -fields[0].ravel()])
        coef, *_ = np.linalg.lstsq(A, fwd[0].ravel(), rcond=None)
        biased = coef[0]
        assert abs(biased - D) / D > 0.05, (
            "the coarse forward difference happened to be accurate, so this "
            "test no longer demonstrates the bias it exists to pin"
        )

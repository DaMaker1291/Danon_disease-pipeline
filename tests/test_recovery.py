class TestIdentifiabilitySweep:
    def test_sweep_marks_unidentifiable_rows_without_error_figures(self, sweep_fixture):
        rows = sweep_fixture
        assert len(rows) == 5
        for r in rows:
            assert isinstance(r, IdentifiabilitySweepRow)
            if not r.identifiable:
                # No error figure may be attached to an undefined answer.
                assert r.recovered_d is None
                assert r.d_relative_error is None
                assert r.r_squared is None
                assert "NOT IDENTIFIABLE" in r.describe()
            else:
                assert r.d_relative_error is not None

    def test_recovery_error_grows_as_diffusion_length_shrinks(self):
        rows = [r for r in transport_identifiability_sweep(
            lambdas=(0.05, 0.10, 0.20)
        ) if r.identifiable]
        assert len(rows) == 3
        lengths = [r.diffusion_length_voxels for r in rows]
        assert lengths == sorted(lengths, reverse=True)
        # All three remain inside a usable band -- the point is that D stays
        # recoverable well above the criterion, then stops being recoverable.
        assert all(r.d_relative_error < 0.10 for r in rows)

    def test_sweep_covers_both_sides_of_the_boundary(self, sweep_fixture):
        assert any(r.identifiable for r in sweep_fixture)
        assert any(not r.identifiable for r in sweep_fixture)



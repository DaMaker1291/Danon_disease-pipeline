class TestTransportRecovery:
    @pytest.fixture(scope="class")
    def recovery(self, transport_fixture):
        return transport_fixture

    def test_recovers_both_constants_inside_a_few_percent(self, recovery):
        assert isinstance(recovery, TransportRecovery)
        assert recovery.d_relative_error < 0.10
        assert recovery.lambda_relative_error < 0.10
        assert recovery.max_relative_error < 0.10

    def test_fit_is_near_exact_and_the_design_is_informative(self, recovery):
        assert recovery.r_squared > 0.999
        # If this drops towards zero the fit says nothing about D, whatever the
        # R^2 is -- which was the original failure mode.
        assert recovery.diagnostics.diffusion_to_clearance_signal > 0.1

    def test_recovered_values_are_absolute_not_targets(self, recovery):
        """The numbers must land where the maths puts them, not where a poster wants.

        Close to the planted value, but not to a suspicious number of digits.
        """
        assert recovery.recovered_d != pytest.approx(recovery.planted_d, abs=1e-9)
        assert recovery.d_relative_error > 1e-4

    def test_assertion_passes_on_a_good_recovery(self, recovery):
        assert_transport_recovery(recovery)

    def test_assertion_fails_on_a_degenerate_design(self):
        """High R^2 with no D-signal must fail, not pass."""
        bad = TransportRecovery(
            planted_d=0.35, planted_lambda=0.10, recovered_d=9.0, recovered_lambda=3.0,
            r_squared=0.9999, n_equations=100, n_times=5, n_steps_used=5,
            grid_shape=(16, 16, 16), source_sigma_voxels=2.5, dt=0.01,
            time_range=(1.0, 2.0), condition_number=2.0, peak_concentration=1.0,
            diagnostics=IdentifiabilityDiagnostic(
                planted_d=0.35, planted_lambda=0.10, voxel_mm=1.0,
                diffusion_length_voxels=2.65, diffusion_length_mm=2.65,
                grid_points_per_diffusion_length=2.65,
                diffusion_to_clearance_signal=1e-6, identifiable=True,
                reason="synthetic",
            ),
        )
        with pytest.raises(RecoveryFailed, match="cannot constrain D"):
            assert_transport_recovery(bad)

    def test_assertion_fails_on_large_parameter_error(self, recovery):
        with pytest.raises(RecoveryFailed, match="not recovered within"):
            assert_transport_recovery(recovery, max_relative_error=1e-6)

    def test_stability_limit_is_enforced_against_the_engine_dt(self):
        with pytest.raises(ValueError, match="forward-Euler stability"):
            transport_recovery(planted_d=5.0, planted_lambda=0.1, engine_dt=0.5)

    def test_boundary_contamination_is_measured_not_assumed(self, recovery):
        """The analytic field is infinite-domain; the stencil is zero-flux."""
        assert recovery.peak_concentration > 0
        # If the grid were too small this would approach order 1.
        assert recovery.diagnostics.identifiable

    def test_recovery_is_deterministic(self):
        a = transport_recovery(n_times=6)
        b = transport_recovery(n_times=6)
        assert a.recovered_d == b.recovered_d
        assert a.recovered_lambda == b.recovered_lambda



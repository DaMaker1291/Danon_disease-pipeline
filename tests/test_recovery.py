# The ground truth must be an independent solver
# ---------------------------------------------------------------------------


class TestAnalyticGroundTruth:
    def test_field_satisfies_the_continuous_pde_analytically(self):
        """The planted field must obey dC/dt = D*Lap(C) - lambda*C in the continuum.

        Checked by finite differences against the analytic partial derivatives,
        not against the engine's stencil -- this pins that the generator is a
        genuine solution rather than something merely plausible.
        """
        D, lam, g = 0.35, 0.10, 32
        t = 12.0
        kw = dict(planted_d=D, planted_lambda=lam, grid_size=g, sigma_voxels=2.0)
        fields = analytic_point_source_field(times=[t], **kw)
        h = 1e-4
        plus = analytic_point_source_field(times=[t + h], **kw)
        minus = analytic_point_source_field(times=[t - h], **kw)
        ddt = (plus - minus) / (2 * h)
        from danon.recovery import _engine_laplacian

        residual = ddt - (D * _engine_laplacian(fields[0]) - lam * fields[0])
        # Compare against the magnitude of the terms themselves.
        scale = np.abs(ddt).max()
        assert np.abs(residual).max() / scale < 0.05

    def test_guard_floor_is_separate_from_the_design_width(self):
        """The singularity guard must not be the caller's design constraint."""
        # sigma at t=1 with D=0.35 is sqrt(0.7)=0.837 voxels: below the default
        # singularity guard of 1.0, so this must raise.
        with pytest.raises(ValueError, match="singularity guard"):
            analytic_point_source_field(
                planted_d=0.35, planted_lambda=0.1, times=[1.0]
            )
        # The same time is fine when the guard is relaxed, even though it is far
        # below the 2.5-voxel design width a series would use.
        out = analytic_point_source_field(
            planted_d=0.35, planted_lambda=0.1, times=[1.0], min_sigma_voxels=0.5
        )
        assert np.isfinite(out).all() and out.max() > 0

    def test_times_must_be_positive(self):
        with pytest.raises(ValueError, match="strictly positive"):
            analytic_point_source_field(
                planted_d=0.35, planted_lambda=0.1, times=[0.0]
            )



class TestIdentifiability:
    def test_diffusion_length_is_the_criterion(self):
        d = assess_transport_identifiability(0.35, 0.10)
        assert isinstance(d, IdentifiabilityDiagnostic)
        assert d.diffusion_length_voxels == pytest.approx(math.sqrt(2 * 0.35 / 0.10))
        assert d.identifiable is True
        assert "spans" in d.reason

    def test_the_sketch_pair_is_refused_and_says_why(self):
        """D=0.15, lambda=0.80 gives a 0.61-voxel diffusion length."""
        d = assess_transport_identifiability(0.15, 0.80)
        assert d.identifiable is False
        assert d.diffusion_length_voxels < 1.0
        assert "cleared before it crosses a voxel" in d.reason

    def test_signal_ratio_is_not_predicted_from_the_planted_pair(self):
        """It is a measured outcome, so the diagnostic must leave it unset."""
        d = assess_transport_identifiability(0.35, 0.10)
        assert math.isnan(d.diffusion_to_clearance_signal)

    def test_recovery_refuses_a_non_identifiable_pair(self):
        with pytest.raises(RecoveryFailed, match="non-identifiable"):
            transport_recovery(planted_d=0.15, planted_lambda=0.80)

    def test_time_window_refuses_when_resolvability_and_clearance_do_not_overlap(self):
        with pytest.raises(ValueError, match="no usable window"):
            infer_times(0.02, 2.0, sigma_voxels=4.0, n_times=5)

    def test_time_window_spans_resolvability_to_clearance(self):
        t = infer_times(0.35, 0.10, sigma_voxels=2.5, n_times=6)
        assert t[0] == pytest.approx(2.5 ** 2 / (2 * 0.35))
        assert t[-1] == pytest.approx(2.5 / 0.10)
        assert t == sorted(t) and len(t) == 6

    def test_negative_or_zero_constants_are_rejected(self):
        with pytest.raises(ValueError):
            assess_transport_identifiability(0.0, 0.1)
        with pytest.raises(ValueError):
            assess_transport_identifiability(0.35, 0.0)



class TestCoxRecovery:
    @pytest.fixture(scope="class")
    def recovery(self, cox_fixture):
        return cox_fixture

    def test_planted_hazard_ratios_are_recovered(self, recovery):
        assert isinstance(recovery, CoxRecovery)
        assert recovery.max_hr_relative_error < 0.15
        for planted, recovered in zip(
            recovery.planted_hazard_ratios, recovery.recovered_hazard_ratios
        ):
            assert recovered == pytest.approx(planted, rel=0.2)

    def test_fitted_pipeline_reaches_the_oracle_ceiling(self, recovery):
        """The load-bearing number.

        The oracle scores with the *true* linear predictor, so it is the best any
        estimator on this data can do. A fitted value sitting at the oracle means
        the real-cohort C-index measures the covariates, not a lossy estimator.
        """
        assert math.isfinite(recovery.oracle_c_index)
        assert recovery.oracle_c_index > 0.5
        assert recovery.c_index_loss_vs_oracle < 0.05

    def test_tolerance_is_expressed_in_standard_errors(self, recovery):
        """A 24% miss is not bias if its standard error is 13%."""
        assert recovery.n_cohorts >= 5
        assert all(se > 0 for se in recovery.hr_standard_errors)
        assert all(math.isfinite(d) for d in recovery.hr_sigma_deviations)
        assert recovery.max_sigma_deviation < 3.0

    def test_too_few_cohorts_cannot_test_bias_and_is_refused(self, recovery):
        """A 3-cohort error bar has 2 df and produced a spurious 22-sigma result."""
        from dataclasses import replace as _replace

        for bad_n in (1, 3, 4):
            thin = _replace(recovery, n_cohorts=bad_n)
            with pytest.raises(RecoveryFailed, match="bias is indistinguishable"):
                assert_cox_recovery(thin)

    def test_flat_percentage_tolerance_still_available_when_forced(self, recovery):
        with pytest.raises(RecoveryFailed, match="not recovered within"):
            assert_cox_recovery(recovery, max_hr_relative_error=1e-6)

    def test_oracle_is_above_the_fitted_fold_average_or_level_with_it(self, recovery):
        # A fitted pipeline cannot systematically beat the true predictor; small
        # fold noise can put it marginally above, so the assertion is on the gap.
        assert abs(recovery.c_index_loss_vs_oracle) < 0.05

    def test_assertion_passes_on_a_good_recovery(self, recovery):
        assert_cox_recovery(recovery)

    def test_assertion_fails_when_bias_exceeds_the_error_bar(self, recovery):
        from dataclasses import replace as _replace

        biased = _replace(
            recovery,
            recovered_hazard_ratios=tuple(
                10.0 * x for x in recovery.recovered_hazard_ratios
            ),
        )
        with pytest.raises(RecoveryFailed, match="bias, not sampling noise"):
            assert_cox_recovery(biased)

    def test_assertion_fails_when_the_pipeline_loses_signal(self, recovery):
        with pytest.raises(RecoveryFailed, match="below the oracle"):
            assert_cox_recovery(recovery, max_c_index_shortfall=-1.0)

    def test_planted_cohort_is_deterministic_and_reproducible(self):
        a, Xa, ra, ba = planted_cox_cohort(n_patients=200, seed=1)
        b, Xb, rb, bb = planted_cox_cohort(n_patients=200, seed=1)
        assert np.array_equal(Xa, Xb)
        assert np.array_equal(ra, rb)
        assert np.array_equal(ba, bb)
        assert np.allclose(ra, Xa @ ba)

    def test_planted_cohort_has_variation_in_every_covariate(self):
        rows, X, risk, beta = planted_cox_cohort(n_patients=300, seed=2)
        assert len(rows) == 300
        assert X.std(axis=0).min() > 0
        assert risk.std() > 0

    def test_planted_cohort_is_censored_like_real_data(self):
        """The first version censored nobody, so the censoring path was untested."""
        rows, X, risk, beta = planted_cox_cohort(
            n_patients=1500, seed=0, target_censoring_fraction=0.45
        )
        events = sum(r.event for r in rows)
        assert 0 < events < len(rows), "a cohort with no censoring is not glioma"
        assert 0.30 < 1 - events / len(rows) < 0.65

    def test_planted_cohort_median_survival_matches_the_target(self):
        """A ~26-day median was what hand-picked rates produced; solve instead."""
        from danon.evotwin import kaplan_meier, km_median

        rows, _, _, _ = planted_cox_cohort(
            n_patients=2000, seed=3, target_median_survival_days=444.0
        )
        km = kaplan_meier([r.time_days for r in rows], [r.event for r in rows])
        median = km_median(km)
        assert median == pytest.approx(444.0, rel=0.20)

    def test_solved_rates_are_monotone_in_the_targets(self):
        """Bisection must actually respond to the target, not land on a constant."""
        short, _, _, _ = planted_cox_cohort(
            n_patients=400, seed=4, target_median_survival_days=200.0
        )
        long_, _, _, _ = planted_cox_cohort(
            n_patients=400, seed=4, target_median_survival_days=800.0
        )
        assert np.mean([r.time_days for r in short]) < np.mean(
            [r.time_days for r in long_]
        )

    def test_oracle_c_index_on_a_perfectly_ordered_score_is_one(self):
        times = np.array([10.0, 20.0, 30.0, 40.0])
        events = np.ones(4, dtype=int)
        risk = np.array([4.0, 3.0, 2.0, 1.0])
        assert oracle_c_index(risk, times, events) == pytest.approx(1.0)

    def test_oracle_c_index_on_a_reversed_score_is_zero(self):
        times = np.array([10.0, 20.0, 30.0, 40.0])
        events = np.ones(4, dtype=int)
        risk = np.array([1.0, 2.0, 3.0, 4.0])
        assert oracle_c_index(risk, times, events) == pytest.approx(0.0)



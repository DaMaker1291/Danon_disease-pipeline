"""
Every artifact the frontend renders, generated by RUNNING the real modules.

WHY THIS EXISTS
---------------
The UI used to contain invented numbers: a hardcoded flow-telemetry object, a
clinical curve synthesised from a fitted exponential, a lipid composition, a
construct map, and a 24-phase matrix with nothing behind it. Those numbers
were indistinguishable from the real ones on screen, which is the worst
possible failure mode for a tool whose whole claim is that its numbers come
from somewhere.

This module runs the repository's own engines and writes one JSON document
per view, so every figure on screen is a recorded engine output:

  pipeline      api_server.run_full_pipeline(constraints)  -> 24 phases,
                Pareto front, sequence, mutations, Horizon-2 metrics,
                translational gates
  microfluidics danon.microfluidics_core.MicrofluidicsCore -> Reynolds,
                shear, Péclet, pressure drop, velocity + concentration
                profiles, and the channel geometry that produced them
  lnp           danon.lnp_generator.DanonLNPGenerator     -> scored
                candidates with real lipid identities and fractions
  clinical      danon.cell_simulator.DanonCellSimulator    -> dose-response
                panel, per-mutation rescue, and the UCL-comparison scores
  construct     danon.construct_builder.ConstructBuilder   -> the real
                plasmid segment map, in base pairs

HONESTY RULES HELD HERE
-----------------------
* each artifact records the exact module call that produced it, so a reader
  can reproduce it, and a `provenance` map of what is real vs modelled;
* nothing is regenerated at render time: the JSON is the artifact, and the UI
  reports a missing artifact instead of substituting a plausible number;
* these are MODEL outputs (the cell simulator is an 8-ODE model; the pipeline
  is a design engine), not measurements -- `notes` says so in every file.
"""


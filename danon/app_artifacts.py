def build_lnp_artifact(batch_size: int = 48, top_n: int = 8) -> Dict[str, Any]:
    """Score real LNP candidates and record the best formulation + spread."""
    from danon.config import DanonConfig
    from danon.lnp_generator import DanonLNPGenerator

    config = DanonConfig()
    generator = DanonLNPGenerator(config)
    scored = generator.score_candidates(generator.generate_candidates(0, batch_size))
    scored = sorted(scored, key=lambda c: c.fitness, reverse=True)

    sizes = [float(c.particle_size_nm) for c in scored]
    fitness = [float(c.fitness) for c in scored]
    best = scored[0]
    composition = [
        {"name": best.ionizable_lipid, "role": "ionizable", "color": "#3b82f6",
         "frac": float(best.ionizable_frac)},
        {"name": "Cholesterol", "role": "structural", "color": "#f59e0b",
         "frac": float(best.cholesterol_frac)},
        {"name": best.helper_lipid, "role": "helper", "color": "#22c55e",
         "frac": float(best.helper_frac)},
        {"name": best.peg_lipid, "role": "PEG", "color": "#a78bfa",
         "frac": float(best.peg_frac)},
    ]

    return _artifact(
        key="lnp",
        title="LNP formulation search",
        source=(
            "danon.lnp_generator.DanonLNPGenerator(DanonConfig())"
            f".generate_candidates(0, {batch_size}) + score_candidates"
        ),
        data={
            "best": _plain(best),
            "top_candidates": [_plain(c) for c in scored[:top_n]],
            "composition": composition,
            "summary": {
                "n_candidates": len(scored),
                "mean_size_nm": float(np.mean(sizes)),
                "sd_size_nm": float(np.std(sizes)),
                "mean_fitness": float(np.mean(fitness)),
                "best_fitness": float(fitness[0]),
                "worst_fitness": float(fitness[-1]),
                "size_range_nm": [float(min(sizes)), float(max(sizes))],
            },
            "ionizable_lipids_seen": sorted({c.ionizable_lipid for c in scored}),
            "peg_lipids_seen": sorted({c.peg_lipid for c in scored}),
        },
        notes=[
            "formulation scores come from the generator's own heuristic model "
            "(cardiac delivery, hepatic avoidance, endosomal escape, size, immune "
            "activation); they are design priorities, not measured potencies",
            "particle size is predicted, not light-scattering measured",
            "no formulation has been manufactured or dosed",
        ],
        provenance={
            "lipid_chemistry_vocabulary": EvidenceStatus.ESTABLISHED,
            "fitness_model": EvidenceStatus.UNKNOWN,
            "predicted_size_matches_measured_size": EvidenceStatus.UNKNOWN,
            "formulation_is_a_validated_medicine": EvidenceStatus.PROVEN_FAILED,
        },
    )



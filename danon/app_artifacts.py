def build_clinical_artifact(vector_copy_number: float = 10.0) -> Dict[str, Any]:
    """Real cell-simulator outputs: dose response, mutation classes, anchors."""
    from danon.cell_simulator import DanonCellSimulator

    sim = DanonCellSimulator()
    dose_response = _plain(sim.dose_response_panel(candidate_id=0))
    mutation_rows = _plain(sim.compare_mutation_types(vector_copy_number=vector_copy_number))

    benchmark: Dict[str, Any] = {}
    for name, fn in (("ucl_trial_score", sim.utcl_score), ("platform_best_score", sim.our_best_score)):
        try:
            benchmark[name] = float(fn())
        except Exception as exc:  # pragma: no cover - reported, never invented
            benchmark[name] = {"error": str(exc)}

    return _artifact(
        key="clinical",
        title="Modelled cardiomyocyte rescue (8-ODE cell simulator)",
        source=(
            "danon.cell_simulator.DanonCellSimulator.dose_response_panel + "
            f"compare_mutation_types(vcn={vector_copy_number}) + benchmark scores"
        ),
        data={
            "dose_response": dose_response,
            "mutation_comparison": mutation_rows,
            "vector_copy_number": vector_copy_number,
            "benchmark": benchmark,
        },
        notes=[
            "every curve here is an 8-ODE MODEL of one cardiomyocyte with "
            "literature-calibrated parameters, not a measurement and not patient data",
            "the UCL comparison is a score against a published trial's reported "
            "figures, not a head-to-head result",
            "no cell, animal, or human has been exposed to this construct",
        ],
        provenance={
            "lamp2b_loss_mechanism": EvidenceStatus.ESTABLISHED,
            "ode_parameterisation": EvidenceStatus.UNKNOWN,
            "model_matches_measured_rescue": EvidenceStatus.UNKNOWN,
            "model_is_clinical_evidence": EvidenceStatus.PROVEN_FAILED,
        },
    )



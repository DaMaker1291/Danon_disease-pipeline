def _now() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def _plain(obj: Any) -> Any:
    """Make an engine return value JSON-safe without losing numbers."""
    if is_dataclass(obj):
        return _plain(asdict(obj))
    if hasattr(obj, "model_dump"):
        return _plain(obj.model_dump())
    if isinstance(obj, dict):
        return {str(k): _plain(v) for k, v in obj.items()}
    if isinstance(obj, (list, tuple)):
        return [_plain(v) for v in obj]
    if isinstance(obj, np.ndarray):
        return _plain(obj.tolist())
    if isinstance(obj, (np.integer,)):
        return int(obj)
    if isinstance(obj, (np.floating,)):
        return float(obj)
    if isinstance(obj, (np.bool_,)):
        return bool(obj)
    return obj


def _artifact(
    key: str,
    title: str,
    source: str,
    data: Dict[str, Any],
    notes: List[str],
    provenance: Dict[str, EvidenceStatus],
) -> Dict[str, Any]:
    return {
        "key": key,
        "title": title,
        "generated_utc": _now(),
        "source": source,
        "notes": list(notes),
        "provenance": {k: v.value for k, v in provenance.items()},
        "data": _plain(data),
    }


# ---------------------------------------------------------------------------
# pipeline (phases, capsid, sequence, Pareto front, translational gates)
# ---------------------------------------------------------------------------


def build_pipeline_artifact(
    candidate_pool: int = 240,
    random_seed: int = 42,
) -> Dict[str, Any]:
    """Run the real 24-phase pipeline once and record the whole result.

    The candidate pool is deliberately modest: this artifact exists so every
    pipeline-driven view has real content without a backend running. The
    constraints used are recorded inside the artifact so the UI can say which
    run a viewer is looking at.
    """
    from api_server import PipelineConstraints, run_full_pipeline

    constraints = PipelineConstraints(candidate_pool=candidate_pool, random_seed=random_seed)
    result = run_full_pipeline(constraints)

    return _artifact(
        key="pipeline",
        title="AAV9-LAMP2B design pipeline (24 phases)",
        source=(
            "api_server.run_full_pipeline(PipelineConstraints("
            f"candidate_pool={candidate_pool}, random_seed={random_seed}))"
        ),
        data={**_plain(result), "constraints": _plain(constraints.model_dump())},
        notes=[
            "engine output, not an experiment: sequences and scores come from the "
            "design pipeline's own scorers (NSGA-II Pareto selection, "
            "Poisson-Boltzmann charge masking, Horizon-2 phase gates)",
            "the capsid sequence has never been synthesised, expressed, or dosed",
            "this is a precomputed run at the recorded constraints; re-run the API "
            "to evaluate different constraints",
        ],
        provenance={
            "pipeline_logic": EvidenceStatus.ESTABLISHED,
            "wild_type_aav9_capsid_and_lamp2b_cds": EvidenceStatus.ESTABLISHED,
            "designed_mutations_and_promoter": EvidenceStatus.UNKNOWN,
            "translational_readiness_scores": EvidenceStatus.UNKNOWN,
            "sequence_is_a_validated_therapy": EvidenceStatus.PROVEN_FAILED,
        },
    )



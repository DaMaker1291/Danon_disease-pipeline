def build_structure_artifact() -> Dict[str, Any]:
    """The real AAV9 capsid: deposited coordinates + the deposit's own symmetry.

    Every number here is read from PDB 3UX1 (chain A) and from its
    `REMARK 350 BIOMT` operators. The capsid viewer used to draw an idealised
    icosphere whose 20 "protrusions" sat on perfect dodecahedron vertices and
    whose surface charges came from a hand-written coordinate table attributed
    to the wrong serotype; this artifact replaces all of that with the
    deposited geometry.
    """
    from danon.structure import (
        AAV9_STRUCTURE_ID,
        AAV9_STRUCTURE_METHOD,
        AAV9_STRUCTURE_REFERENCE,
        AAV9_STRUCTURE_TITLE,
        MISLABELED_STRUCTURE_ACTUAL,
        MISLABELED_STRUCTURE_ID,
        VR_REGION_WINDOWS,
        load_aav9_capsid,
    )

    capsid = load_aav9_capsid()
    contact = capsid.contact_numbers()
    exposure = capsid.exposure_proxy()
    radius = capsid.residue_radius()

    residues = [
        {
            "vp1": int(r.resseq),
            "stored": int(r.design_position),
            "aa": _ONE_TO_THREE.get(r.aa, "UNK"),
            "x": round(r.x, 3),
            "y": round(r.y, 3),
            "z": round(r.z, 3),
            "radius_a": round(float(radius[i]), 3),
            "contacts": int(contact[i]),
            "exposure_proxy": round(float(exposure[i]), 4),
        }
        for i, r in enumerate(capsid.residues)
    ]

    vr = {}
    for region, (lo, hi) in VR_REGION_WINDOWS.items():
        table = capsid.region_coordinate_table(region)
        vr[region] = {
            "vp1_range": [lo, hi],
            "stored_range": [lo - 262, hi - 262],
            "residues": [
                {
                    "vp1": pos + 262,
                    "stored": pos,
                    "aa": _ONE_TO_THREE.get(
                        next(r.aa for r in capsid.region_residues(region) if r.design_position == pos),
                        "UNK",
                    ),
                    "x": round(v[0], 3),
                    "y": round(v[1], 3),
                    "z": round(v[2], 3),
                    "exposure_proxy": round(v[3], 4),
                }
                for pos, v in sorted(table.items())
            ],
        }

    return _artifact(
        key="structure",
        title=f"AAV9 capsid structure ({AAV9_STRUCTURE_ID}) -- deposited coordinates, deposited symmetry",
        source=(
            f"danon.structure.load_aav9_capsid() over PDB {AAV9_STRUCTURE_ID}; "
            f"coordinates and REMARK 350 BIOMT operators read from "
            f"data/pdb/{AAV9_STRUCTURE_ID}.pdb"
        ),
        data={
            "structure_id": AAV9_STRUCTURE_ID,
            "title": AAV9_STRUCTURE_TITLE,
            "method": AAV9_STRUCTURE_METHOD,
            "reference": AAV9_STRUCTURE_REFERENCE,
            "sha256": capsid.sha256,
            "mislabeled_prior_id": MISLABELED_STRUCTURE_ID,
            "mislabeled_prior_id_actual": MISLABELED_STRUCTURE_ACTUAL,
            "geometry": {
                "subunits": capsid.subunit_count,
                "ca_atoms": capsid.atom_count,
                "asymmetric_unit_residues": len(capsid.residues),
                "centre": [round(float(v), 3) for v in capsid.center],
                "inner_radius_a": round(capsid.inner_radius, 3),
                "mean_radius_a": round(capsid.mean_radius, 3),
                "outer_radius_a": round(capsid.outer_radius, 3),
                "protrusions": len(capsid.protrusion_axes()),
                "three_fold_axis_lines": len(capsid.three_fold_axes),
                "five_fold_axis_lines": len(capsid.five_fold_axes),
                "two_fold_axis_lines": len(capsid.two_fold_axes),
            },
            "asymmetric_unit": residues,
            "symmetry_operators": [
                {
                    "index": op.index,
                    "order": op.order,
                    "angle_deg": round(op.angle_deg, 4),
                    "axis": None if op.axis is None else [round(float(v), 6) for v in op.axis],
                    "rotation": [[round(float(v), 8) for v in row[:3]] for row in op.matrix[:3]],
                    "translation": [round(float(v), 6) for v in op.matrix[:3, 3]],
                }
                for op in capsid.classified
            ],
            "axes": {
                f"{order}_fold": {
                    "lines": [[round(float(v), 6) for v in ax] for ax in capsid.axes(order)],
                    "line_count": len(capsid.axes(order)),
                }
                for order in (5, 3, 2)
            },
            "vr_regions": vr,
            "position_frame": {
                "positions_are": "1-based design positions",
                "edits_index": "sequence[position - 1]",
                "position_to_vp1_offset": 262,
                "index_offset": 263,
            },
        },
        notes=[
            "Coordinates are C-alpha only: this is a backbone trace of one "
            "deposited model, not an atomic surface.",
            "The 60-subunit assembly is generated from the entry's own REMARK 350 "
            "BIOMT matrices -- the depositors' operators, not a reconstruction.",
            "`exposure_proxy` is radius / outer_radius (a radial measure). It is "
            "NOT solvent-accessible surface area.",
            "`contacts` counts C-alpha neighbours within 10 A across the assembly "
            "-- a contact number, not an energy.",
            "The VR-IV / VR-VIII window boundaries are this repository's design "
            "windows; the residues inside them are the deposit's.",
        ],
        provenance={
            "ca_coordinates": EvidenceStatus.ESTABLISHED,
            "symmetry_operators": EvidenceStatus.ESTABLISHED,
            "assembly_geometry": EvidenceStatus.ESTABLISHED,
            "residue_numbering": EvidenceStatus.ESTABLISHED,
            "exposure_proxy": EvidenceStatus.UNKNOWN,
            "region_boundaries": EvidenceStatus.UNKNOWN,
            "engineered_variant_geometry": EvidenceStatus.UNKNOWN,
        },
    )



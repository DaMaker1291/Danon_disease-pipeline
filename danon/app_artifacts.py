def build_app_artifacts(
    keys: Optional[List[str]] = None,
    log: Optional[callable] = None,
) -> Dict[str, Dict[str, Any]]:
    """Build every requested artifact (default: all of them)."""
    chosen = list(keys or BUILDERS)
    unknown = [k for k in chosen if k not in BUILDERS]
    if unknown:
        raise ValueError(f"unknown artifact keys: {unknown}; known: {sorted(BUILDERS)}")

    out: Dict[str, Dict[str, Any]] = {}
    for key in chosen:
        payload = BUILDERS[key]()
        out[key] = payload
        if log is not None:
            log(f"  built {key:<14s} ({len(json.dumps(payload['data'])):>7,d} bytes of data)")
    if not out:
        raise ValueError("no artifacts were built")
    return out


def write_app_artifacts(
    out_dir: str = "outputs_real/app_artifacts",
    mirror_dir: Optional[str] = "frontend/public/artifacts",
    keys: Optional[List[str]] = None,
    log: Optional[callable] = None,
) -> Dict[str, List[str]]:
    """Write each artifact to disk (and to the frontend's public folder).

    Returns {key: [paths written]}. The frontend copy is byte-identical to the
    canonical one, so the UI cannot be showing a stale or different artifact
    than the one the repository holds.
    """
    artifacts = build_app_artifacts(keys=keys, log=log)
    written: Dict[str, List[str]] = {}
    for key, payload in artifacts.items():
        blob = json.dumps(payload, indent=1)
        paths = []
        for directory in (out_dir, mirror_dir):
            if not directory:
                continue
            os.makedirs(directory, exist_ok=True)
            path = os.path.join(directory, f"{key}.json")
            with open(path, "w") as fh:
                fh.write(blob)
            paths.append(path)
        written[key] = paths
        if log is not None:
            log(f"  wrote {key:<14s} -> {', '.join(paths)}")
    return written



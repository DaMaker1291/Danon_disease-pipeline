"""One config, one command, the full 365-day paired trial.

WHY THIS MODULE EXISTS
----------------------
Every other measurement in this repository runs on inputs that are either
gigabytes of re-downloadable cache or a case ID hard-coded inside a cohort
script. Both are the right call for provenance and both leave the same gap: no
single command runs the twin on an input a reviewer chooses, and the one branch
that makes the MTD-vs-steering result mechanistic -- a spatially heterogeneous
drug source -- has no committed input at all.

So this module ships two things:

  * ``build_sample_dataset`` writes a tiny synthetic phantom (three NIfTI
    volumes plus a config) generated by the engine's OWN
    ``make_gbm_phantom``, so what is committed is exactly what the code
    produces and the dataset cannot drift from the generator;
  * ``run_config`` reads a config and runs the real paired trial --
    ``CollateralSwitchPolicy`` against ``MTDPolicy``, same geometry, same
    seeds -- through the same ``TumorEvolutionSimulator`` the app calls.

WHAT THE SAMPLE DATASET IS NOT
------------------------------
It is **not** patient data, and the directory name is the only sense in which
it is BIDS: the layout is BIDS-shaped (``sub-<label>/<datatype>/<file>`` and a
``dataset_description.json``) because that is the convention a reviewer looks
in, but BIDS proper describes participant data and this is a phantom.
``dataset_description.json`` and every report this module emits say so in
plain words rather than relying on the reader noticing the directory name.

The phantom has no measured anything. Its proliferative map is the engine's
ruffled-boundary sphere with a hypoxic core; its vessel map is synthetic
penetrating chords. Constants (`DEFAULT_CLONES`, `DEFAULT_DRUGS`) are the
repository's declared assumptions, unchanged. Nothing here is evidence about a
patient, and no number this module prints is a clinical prediction.
"""

from __future__ import annotations

import argparse
import json
import os
import statistics
import sys
from typing import Any, Dict, List, Optional, Sequence, Tuple

import numpy as np

from danon.evosteer import (
    CollateralSwitchPolicy,
    MTDPolicy,
    TumorEvolutionSimulator,
    make_gbm_phantom,
)
from danon.imaging import from_nifti_mask, write_nifti

# ---------------------------------------------------------------------------
# The committed sample
# ---------------------------------------------------------------------------

SAMPLE_ROOT = os.path.join("data", "sample_bids")
SAMPLE_SUBJECT = "sub-01"
PHANTOM_SIZE = 24
PHANTOM_SEED = 0
SAMPLE_DAYS = 365
SAMPLE_SEEDS: Tuple[int, ...] = (101, 102, 103)
SAMPLE_ARMS: Tuple[str, ...] = ("mtd", "steering")
SAMPLE_RESISTANT_FRACTION = 0.005

#: The only two policies this harness pairs. Both are engine classes, so a
#: config selects an arm by name and cannot invent one.
ARM_POLICIES = {"mtd": MTDPolicy, "steering": CollateralSwitchPolicy}

#: Volume -> what the loader does with it. `vessels` is also the map the
#: optional heterogeneous-diffusion branch is built from, which is why one
#: field drives both the drug source and D(x).
_INPUT_ROLES = ("mask", "proliferative", "vessels")


def sample_config_path(root: str = SAMPLE_ROOT) -> str:
    """Path of the config the bare ``python -m danon.reproduce`` runs."""
    return os.path.join(root, SAMPLE_SUBJECT, f"{SAMPLE_SUBJECT}_twin.json")


def _portable(path: str) -> str:
    """Repo-relative when the path is inside the repo, so a report is portable.

    A committed report carrying `C:\\Users\\...` is a report only its author can
    follow, and it is how a generated artifact starts to look like a source
    file. Paths outside the repository stay absolute and stay unportable -- that
    is the honest thing to record.
    """
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    try:
        rel = os.path.relpath(os.path.abspath(path), root)
    except ValueError:  # different drive on Windows
        return os.path.abspath(path)
    return rel.replace(os.sep, "/") if not rel.startswith("..") else os.path.abspath(path)


def _write_uint8_pair(path: str, arr: np.ndarray, voxel_mm: float) -> str:
    """Write a [0, 1] float map as uint8 NIfTI, saturating rather than wrapping.

    ``write_nifti`` stores uint8, and the loader's own rule is that a map whose
    maximum exceeds 1.5 is on a raw intensity scale and gets divided by its
    maximum. So a [0, 1] map written as ``round(255 * x)`` round-trips back
    through ``/255`` at a quantization of 1/255 per voxel -- small, and
    MEASURED in the test suite rather than assumed harmless.
    """
    scaled = np.clip(np.rint(arr * 255.0), 0.0, 255.0)
    return write_nifti(path, scaled, voxel_sizes=(voxel_mm,) * 3)


def build_sample_dataset(
    root: str = SAMPLE_ROOT,
    *,
    size: int = PHANTOM_SIZE,
    seed: int = PHANTOM_SEED,
) -> Dict[str, Any]:
    """Write the committed sample dataset; return what was written, measured.

    The returned manifest is rebuilt from the arrays that were written, not
    from the phantom in memory, so a manifest that disagrees with the files on
    disk is impossible to produce.
    """
    geom = make_gbm_phantom(size=size, seed=seed)
    voxel_mm = float(geom.voxel_mm)
    subject_dir = os.path.join(root, SAMPLE_SUBJECT)
    anat_dir = os.path.join(subject_dir, "anat")
    perf_dir = os.path.join(subject_dir, "perf")
    for directory in (anat_dir, perf_dir):
        os.makedirs(directory, exist_ok=True)

    mask_path = os.path.join(subject_dir, f"{SAMPLE_SUBJECT}_mask.nii.gz")
    prolif_path = os.path.join(anat_dir, f"{SAMPLE_SUBJECT}_prolif.nii.gz")
    vessels_path = os.path.join(perf_dir, f"{SAMPLE_SUBJECT}_vessels.nii.gz")

    write_nifti(mask_path, geom.tumor_mask.astype(np.uint8), voxel_sizes=(voxel_mm,) * 3)
    _write_uint8_pair(prolif_path, geom.proliferative, voxel_mm)
    _write_uint8_pair(vessels_path, geom.vessels, voxel_mm)

    description = {
        "Name": "EvoTwin-10X sample twin input (synthetic phantom)",
        "BIDSVersion": "1.9.0",
        "DatasetType": "derivative",
        "GeneratedBy": [
            {
                "Name": "danon.reproduce.build_sample_dataset",
                "Description": (
                    "danon.evosteer.make_gbm_phantom written as NIfTI-1 uint8; "
                    "regenerate with `python -m danon.reproduce build-sample`"
                ),
            }
        ],
        "Synthetic": True,
        "Caveat": (
            "NOT patient data. This is a phantom in a BIDS-SHAPED directory "
            "(sub-<label>/<datatype>/<file>) so the same loader path the app "
            "uses can be exercised with no download. It is not a "
            "BIDS-conformant dataset: BIDS describes participant data. The "
            "phantom's proliferation and vasculature are synthetic, the engine "
            "constants are declared assumptions, and no number a run produces "
            "is a clinical prediction."
        ),
    }
    with open(os.path.join(root, "dataset_description.json"), "w", encoding="utf-8") as fh:
        json.dump(description, fh, indent=2)
        fh.write("\n")

    config = {
        "subject": SAMPLE_SUBJECT,
        "synthetic": True,
        "note": description["Caveat"],
        "inputs": {
            "mask": f"{SAMPLE_SUBJECT}_mask.nii.gz",
            "proliferative": f"anat/{SAMPLE_SUBJECT}_prolif.nii.gz",
            "vessels": f"perf/{SAMPLE_SUBJECT}_vessels.nii.gz",
        },
        "trial": {
            "days": SAMPLE_DAYS,
            "seeds": list(SAMPLE_SEEDS),
            "arms": list(SAMPLE_ARMS),
            "initial_resistant_fraction": SAMPLE_RESISTANT_FRACTION,
            # Homogeneous transport, measured rather than preferred: the
            # heterogeneous operator costs about 19x per run at this grid
            # (16 diffusion sub-steps against 6, and a chunkier stencil per
            # sub-step), so 6 runs take minutes instead of seconds. The flag
            # is exercised at a short horizon by the test suite; a reviewer
            # who wants the D(x) branch on the sample sets this to true and
            # accepts the wall time.
            "diffusion_from_vessels": False,
        },
    }
    with open(sample_config_path(root), "w", encoding="utf-8") as fh:
        json.dump(config, fh, indent=2)
        fh.write("\n")

    # Re-read what landed on disk and measure it, so the manifest describes the
    # files rather than the arrays that were supposed to become them.
    page = from_nifti_mask(mask_path, proliferative_path=prolif_path, vessels_path=vessels_path)
    inside = page.geometry.tumor_mask
    return {
        "root": os.path.abspath(root),
        "config": os.path.abspath(sample_config_path(root)),
        "phantom": {"size": size, "seed": seed},
        "files": {
            "mask": mask_path,
            "proliferative": prolif_path,
            "vessels": vessels_path,
        },
        "geometry": {
            "n_voxels": int(inside.size),
            "n_tumour_voxels": int(page.n_tumour_voxels),
            "tumour_fraction": float(page.n_tumour_voxels / inside.size),
            "voxel_mm": float(voxel_mm),
            "proliferative_source": page.proliferative_source,
            "vasculature_source": page.vasculature_source,
            "proliferative_max": float(page.geometry.proliferative.max()),
            "vessels_max": float(page.geometry.vessels.max()),
            "vessels_min_below_detection": float(
                page.geometry.vessels[inside].min(initial=0.0)
            ),
        },
    }


# ---------------------------------------------------------------------------
# Config intake: refuse what cannot be run, by name and reason
# ---------------------------------------------------------------------------

_REQUIRED_INPUT = "mask"


def load_config(config_path: str) -> Dict[str, Any]:
    """Read and validate a trial config; return absolute paths and typed values.

    Every refusal names the field and the reason. The one refusal worth calling
    out is the empty seed list: a cohort of zero replicates would produce a
    median of nothing, which reads like a null result and is really no
    measurement at all.
    """
    path = os.path.abspath(config_path)
    with open(path, "r", encoding="utf-8") as fh:
        try:
            raw = json.load(fh)
        except json.JSONDecodeError as exc:
            raise ValueError(f"{path} is not valid JSON: {exc}") from exc
    if not isinstance(raw, dict):
        raise ValueError(f"{path}: expected a JSON object, got {type(raw).__name__}")

    inputs = raw.get("inputs")
    if not isinstance(inputs, dict):
        raise ValueError(f"{path}: 'inputs' must be an object naming the volumes")
    base = os.path.dirname(path)

    # Shape of the config first, filesystem last: a config that is malformed in
    # two ways should report the malformation, not whichever file it happened
    # to name first.
    names: Dict[str, Optional[str]] = {}
    for role in _INPUT_ROLES:
        value = inputs.get(role)
        if value is None:
            if role == _REQUIRED_INPUT:
                raise ValueError(f"{path}: 'inputs.{role}' is required")
            names[role] = None
            continue
        if not isinstance(value, str) or not value:
            raise ValueError(f"{path}: 'inputs.{role}' must be a non-empty path")
        names[role] = value

    trial = raw.get("trial")
    if not isinstance(trial, dict):
        raise ValueError(f"{path}: 'trial' must be an object")

    days = trial.get("days", SAMPLE_DAYS)
    if not isinstance(days, int) or isinstance(days, bool) or days < 1:
        raise ValueError(f"{path}: 'trial.days' must be a positive integer, got {days!r}")

    seeds_raw = trial.get("seeds", list(SAMPLE_SEEDS))
    if not isinstance(seeds_raw, (list, tuple)) or not seeds_raw:
        raise ValueError(
            f"{path}: 'trial.seeds' is empty -- an empty cohort is not a null "
            "result, it is no measurement"
        )
    seeds: List[int] = []
    for item in seeds_raw:
        if not isinstance(item, int) or isinstance(item, bool):
            raise ValueError(f"{path}: 'trial.seeds' must be integers, got {item!r}")
        seeds.append(int(item))

    arms_raw = trial.get("arms", list(SAMPLE_ARMS))
    if not isinstance(arms_raw, (list, tuple)) or not arms_raw:
        raise ValueError(f"{path}: 'trial.arms' is empty; nothing would be run")
    arms: List[str] = []
    for arm in arms_raw:
        if arm not in ARM_POLICIES:
            raise ValueError(
                f"{path}: 'trial.arms' entry {arm!r} is not one of "
                f"{sorted(ARM_POLICIES)}"
            )
        arms.append(str(arm))

    r0 = trial.get("initial_resistant_fraction", 0.01)
    if isinstance(r0, bool) or not isinstance(r0, (int, float)):
        raise ValueError(f"{path}: 'trial.initial_resistant_fraction' must be a number")
    if not 0.0 <= float(r0) <= 1.0:
        raise ValueError(
            f"{path}: 'trial.initial_resistant_fraction' must be in [0, 1], got {r0}"
        )

    diffusion_from_vessels = bool(trial.get("diffusion_from_vessels", False))
    if diffusion_from_vessels and names["vessels"] is None:
        raise ValueError(
            f"{path}: 'trial.diffusion_from_vessels' is set but 'inputs.vessels' "
            "names no map to build D(x) from"
        )

    resolved: Dict[str, Optional[str]] = {}
    for role, value in names.items():
        if value is None:
            resolved[role] = None
            continue
        full = value if os.path.isabs(value) else os.path.join(base, value)
        if not os.path.exists(full):
            raise FileNotFoundError(
                f"{path}: 'inputs.{role}' points at {value}, which is not there "
                f"(resolved to {full})"
            )
        resolved[role] = full

    return {
        "config_path": path,
        "subject": str(raw.get("subject", os.path.splitext(os.path.basename(path))[0])),
        "synthetic": bool(raw.get("synthetic", False)),
        "note": raw.get("note"),
        "inputs": resolved,
        "days": int(days),
        "seeds": tuple(seeds),
        "arms": tuple(arms),
        "initial_resistant_fraction": float(r0),
        "diffusion_from_vessels": diffusion_from_vessels,
    }


# ---------------------------------------------------------------------------
# The run: the real paired trial, through the real entry points
# ---------------------------------------------------------------------------


def run_config(config_path: str, *, out_file: Optional[str] = None) -> Dict[str, Any]:
    """Run the paired 365-day trial a config describes; return the report.

    Geometry and transport are shared by both arms -- same simulator
    construction, same D(x) field, same seeds -- so a difference between the
    arms is attributable to the dosing policy alone.
    """
    spec = load_config(config_path)
    page = from_nifti_mask(
        spec["inputs"]["mask"],
        proliferative_path=spec["inputs"]["proliferative"],
        vessels_path=spec["inputs"]["vessels"],
    )
    geometry = page.geometry

    diffusion_field = None
    if spec["diffusion_from_vessels"]:
        from danon.clinical_twin import build_stream3_diffusion_field

        diffusion_field = build_stream3_diffusion_field(
            geometry.vessels, voxel_mm=page.voxel_mm
        )

    runs: Dict[str, List[Dict[str, Any]]] = {arm: [] for arm in spec["arms"]}
    for seed in spec["seeds"]:
        for arm in spec["arms"]:
            sim = TumorEvolutionSimulator(geometry, diffusion_field=diffusion_field)
            traj = sim.run(
                ARM_POLICIES[arm](),
                days=spec["days"],
                initial_resistant_fraction=spec["initial_resistant_fraction"],
                seed=seed,
            )
            runs[arm].append(
                {
                    "seed": seed,
                    "pfs_days": traj.pfs_value(spec["days"]),
                    "progressed": bool(traj.progressed),
                    "final_burden": float(traj.burden_S[-1] + traj.burden_R[-1]),
                    "final_resistant_fraction": float(traj.final_resistant_fraction),
                    "resistant_dominance_day": traj.resistant_dominance_day,
                    "toxicity": float(traj.toxicity),
                }
            )

    arms: Dict[str, Dict[str, Any]] = {}
    for arm, arm_runs in runs.items():
        pfs = [r["pfs_days"] for r in arm_runs]
        burden = [r["final_burden"] for r in arm_runs]
        arms[arm] = {
            "runs": arm_runs,
            "median_pfs_days": float(statistics.median(pfs)),
            "median_final_burden": float(statistics.median(burden)),
            "burden_min": float(min(burden)),
            "burden_max": float(max(burden)),
            # The run's own resolution: without it, any arm-to-arm difference
            # is unreadable against the stochastic spread it sits inside.
            "burden_spread_fraction": (
                float((max(burden) - min(burden)) / statistics.mean(burden))
                if statistics.mean(burden)
                else 0.0
            ),
        }

    paired: Dict[str, Any] = {}
    if len(spec["arms"]) == 2:
        first, second = spec["arms"]
        deltas = [
            b["pfs_days"] - a["pfs_days"]
            for a, b in zip(runs[first], runs[second])
        ]
        paired = {
            "arms": [first, second],
            "pfs_delta_days": deltas,
            "median_pfs_delta_days": float(statistics.median(deltas)),
            "n_pairs_in_disagreement": int(sum(d != 0 for d in deltas)),
            "n_pairs": len(deltas),
        }

    inside = geometry.tumor_mask
    config_display = _portable(spec["config_path"])
    report = {
        "config": config_display,
        "subject": spec["subject"],
        "synthetic": spec["synthetic"],
        "inputs": {
            role: (None if spec["inputs"][role] is None else _portable(spec["inputs"][role]))
            for role in _INPUT_ROLES
        }
        | {
            "proliferative_source": page.proliferative_source,
            "vasculature_source": page.vasculature_source,
        },
        "geometry": {
            "n_voxels": int(inside.size),
            "n_tumour_voxels": int(page.n_tumour_voxels),
            "voxel_mm": float(page.voxel_mm),
            "vessels_median_inside_tumour": float(
                np.median(geometry.vessels[inside]) if inside.any() else 0.0
            ),
            "vessels_max": float(geometry.vessels.max()),
        },
        "trial": {
            "days": spec["days"],
            "seeds": list(spec["seeds"]),
            "arms": list(spec["arms"]),
            "initial_resistant_fraction": spec["initial_resistant_fraction"],
            "transport": (
                "heterogeneous D(x) from the vessel map"
                if diffusion_field is not None
                else "homogeneous (engine's calibrated D)"
            ),
        },
        "arms": arms,
        "paired": paired,
        "how_to_reproduce": f"python -m danon.reproduce run --config {config_display}",
        "caveat": spec["note"],
    }
    if out_file:
        os.makedirs(os.path.dirname(os.path.abspath(out_file)), exist_ok=True)
        with open(out_file, "w", encoding="utf-8") as fh:
            json.dump(report, fh, indent=1)
            fh.write("\n")
    return report


def format_report(report: Dict[str, Any]) -> str:
    """The printed summary. Every line is a measured field of the report."""
    banner = "SYNTHETIC PHANTOM -- not patient data" if report["synthetic"] else "input"
    lines: List[str] = []
    lines.append("=" * 78)
    lines.append(f"EvoTwin-10X paired trial  [{banner}]")
    lines.append("=" * 78)
    geo, trial = report["geometry"], report["trial"]
    lines.append(
        f"  subject {report['subject']}   {geo['n_tumour_voxels']:,} tumour voxels of "
        f"{geo['n_voxels']:,} at {geo['voxel_mm']:g} mm"
    )
    lines.append(
        f"  inputs: proliferative={report['inputs']['proliferative_source']}  "
        f"vasculature={report['inputs']['vasculature_source']}"
    )
    lines.append(
        f"  trial: {trial['days']} days, seeds {trial['seeds']}, "
        f"r0={trial['initial_resistant_fraction']:g}, {trial['transport']}"
    )
    lines.append("")
    lines.append(
        f"  {'arm':10s} {'median PFS':>11s} {'runs at horizon':>16s} "
        f"{'median burden':>14s} {'spread':>8s}"
    )
    for arm, data in report["arms"].items():
        at_horizon = sum(1 for r in data["runs"] if not r["progressed"])
        spread = data["burden_spread_fraction"] * 100.0
        lines.append(
            f"  {arm:10s} {data['median_pfs_days']:>10.1f}d "
            f"{at_horizon:>8d}/{len(data['runs']):<7d} "
            f"{data['median_final_burden']:>14.4g} {spread:>7.1f}%"
        )
    paired = report["paired"]
    if paired:
        a, b = paired["arms"]
        lines.append("")
        lines.append(
            f"  paired by seed ({b} - {a}): median "
            f"{paired['median_pfs_delta_days']:+.1f} d, "
            f"{paired['n_pairs_in_disagreement']}/{paired['n_pairs']} pairs differ"
        )
    lines.append("")
    lines.append(f"  reproduce: {report['how_to_reproduce']}")
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------


def main(argv: Optional[Sequence[str]] = None) -> int:
    """``python -m danon.reproduce`` runs the sample; ``build-sample`` rewrites it."""
    args = list(sys.argv[1:] if argv is None else argv)
    # A bare invocation (or a bare `--config`) is the sample run: the whole
    # point of this module is that one command works on a fresh clone.
    if not args or args[0].startswith("-"):
        args = ["run", *args]

    parser = argparse.ArgumentParser(
        prog="python -m danon.reproduce",
        description="Run the EvoTwin-10X paired trial from a config (no downloads).",
    )
    sub = parser.add_subparsers(dest="command", required=True)

    run = sub.add_parser("run", help="run a config's paired trial")
    run.add_argument(
        "--config",
        default=sample_config_path(),
        help=f"trial config JSON (default: the committed sample, {sample_config_path()})",
    )
    run.add_argument("--out", default=None, help="write the report JSON here")

    build = sub.add_parser(
        "build-sample", help="regenerate the committed sample dataset from the phantom"
    )
    build.add_argument("--root", default=SAMPLE_ROOT, help="dataset directory")
    build.add_argument("--size", type=int, default=PHANTOM_SIZE, help="phantom grid edge")
    build.add_argument("--seed", type=int, default=PHANTOM_SEED, help="phantom seed")

    parsed = parser.parse_args(args)
    if parsed.command == "build-sample":
        manifest = build_sample_dataset(parsed.root, size=parsed.size, seed=parsed.seed)
        geo = manifest["geometry"]
        print(f"wrote {manifest['root']}")
        print(
            f"  {geo['n_tumour_voxels']:,} tumour voxels of {geo['n_voxels']:,} "
            f"({geo['tumour_fraction'] * 100:.1f}%) at {geo['voxel_mm']:g} mm; "
            f"proliferative={geo['proliferative_source']} "
            f"vasculature={geo['vasculature_source']}"
        )
        print(f"  config: {manifest['config']}")
        return 0

    report = run_config(parsed.config, out_file=parsed.out)
    print(format_report(report))
    if parsed.out:
        print(f"\nwrote {os.path.abspath(parsed.out)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
